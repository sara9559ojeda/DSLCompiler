/**
 * Ready-made DSL programs the user can load with one click instead of
 * typing from scratch. Every one of these is real DSL — tests/presets.test.ts
 * compiles each with the actual pipeline and fails on any diagnostic.
 *
 * The language has no triangles, so pointy parts (ears, roofs, tails) are
 * built from stacked rectangles. `conectar` always joins shape centers, so
 * the flowchart connects tiny background-colored anchor circles placed on
 * each box's edge to get edge-to-edge arrows.
 */
export interface DslPreset {
  readonly id: string;
  readonly name: string;
  readonly source: string;
}

const lines = (...statements: string[]): string => `${statements.join("\n")}\n`;

